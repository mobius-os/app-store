import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  assertCompleteCatalogSnapshots,
  REQUIRED_SNAPSHOT_FIELDS,
} from './catalog-snapshot-contract.mjs'
import { calculatePackageFootprint } from './package-footprint.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const catalogPath = resolve(root, 'catalog.json')
const packageMetadataPath = resolve(root, 'package-metadata.json')
const snapshotsPath = resolve(root, 'manifest-snapshots.js')
const localAppsRoot = process.env.MOBIUS_LOCAL_APPS_ROOT
const MAX_FETCHES = 12
let activeFetches = 0
const fetchWaiters = []

async function withFetchSlot(callback) {
  if (activeFetches >= MAX_FETCHES) {
    await new Promise(resolve => fetchWaiters.push(resolve))
  }
  activeFetches += 1
  try {
    return await callback()
  } finally {
    activeFetches -= 1
    fetchWaiters.shift()?.()
  }
}

async function fetchBytes(url, label) {
  return await withFetchSlot(async () => {
    const response = await fetch(url, { cache: 'no-store' })
    if (!response.ok) throw new Error(`${label}: returned HTTP ${response.status}`)
    return Buffer.from(await response.arrayBuffer())
  })
}

function refreshUrl(value, id) {
  const url = new URL(value)
  const parts = url.pathname.split('/').filter(Boolean)
  if (
    url.hostname === 'raw.githubusercontent.com' &&
    parts.length >= 4 &&
    parts[2] === 'main'
  ) {
    // The short raw /main/ form can lag a newly pushed branch tip at some CDN
    // edges. GitHub's ref-qualified route resolves the branch first, then
    // redirects to raw content for that exact ref.
    return new URL(
      `https://github.com/${parts[0]}/${parts[1]}/raw/refs/heads/main/` +
      parts.slice(3).join('/'),
    )
  }
  url.searchParams.set('_mobius_refresh', `${Date.now()}-${id}`)
  return url
}

const catalog = JSON.parse(await readFile(catalogPath, 'utf8'))
if (!Array.isArray(catalog.apps) || catalog.apps.length === 0) {
  throw new Error('catalog.json has no apps')
}

const packages = await Promise.all(catalog.apps.map(async (entry) => {
  if (localAppsRoot) {
    const repoName = String(entry.repo || '').split('/').filter(Boolean).at(-1)
    if (!repoName) throw new Error(`${entry.id}: catalog entry has no repo`)
    const repoRoot = resolve(localAppsRoot, repoName)
    const localPath = resolve(repoRoot, 'mobius.json')
    const manifest = JSON.parse(await readFile(localPath, 'utf8'))
    for (const key of REQUIRED_SNAPSHOT_FIELDS) {
      if (typeof manifest?.[key] !== 'string' || !manifest[key]) {
        throw new Error(`${entry.id}: local manifest is missing ${key}`)
      }
    }
    const footprint = await calculatePackageFootprint(
      manifest,
      path => readFile(resolve(repoRoot, path)),
    )
    return { manifest: { ...manifest, package_footprint: footprint }, footprint }
  }
  // A refresh must observe the current branch tip rather than silently
  // republishing an older snapshot. The durable manifest_url stored in the
  // catalog remains unchanged.
  const manifestUrl = refreshUrl(entry.manifest_url, entry.id)
  const manifest = JSON.parse((await fetchBytes(manifestUrl, `${entry.id}: manifest`)).toString('utf8'))
  for (const key of REQUIRED_SNAPSHOT_FIELDS) {
    if (typeof manifest?.[key] !== 'string' || !manifest[key]) {
      throw new Error(`${entry.id}: manifest is missing ${key}`)
    }
  }
  const footprint = await calculatePackageFootprint(manifest, async path => {
    const fileUrl = refreshUrl(new URL(path, entry.raw_base), `${entry.id}-${path}`)
    return await fetchBytes(fileUrl, `${entry.id}: ${path}`)
  })
  return { manifest: { ...manifest, package_footprint: footprint }, footprint }
}))

const snapshots = {}
const packageMetadata = { schema: 1, apps: {} }
catalog.apps.forEach((entry, index) => {
  snapshots[entry.id] = packages[index].manifest
  packageMetadata.apps[entry.id] = packages[index].footprint
})

assertCompleteCatalogSnapshots(catalog, snapshots)

const generated = `// Generated by scripts/refresh-manifest-snapshots.mjs.\n` +
  `// Install/update still uses manifest_url; these are a resilient first-paint floor.\n` +
  `export const MANIFEST_SNAPSHOTS = ${JSON.stringify(snapshots, null, 2)}\n`

await writeFile(snapshotsPath, generated)
await writeFile(packageMetadataPath, `${JSON.stringify(packageMetadata, null, 2)}\n`)
